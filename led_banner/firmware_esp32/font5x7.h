// Поиск глифа (линейный — их немного, для 10 к/с более чем быстро).
inline const uint8_t* glyphFor(char16_t c) {
  for (const auto& g : FONT5X7) if (g.cp == c) return g.cols;
  // регистронезависимость для латиницы/кириллицы
  if (c >= U'a' && c <= U'z') return glyphFor((char16_t)(c - 32));
  if (c >= U'а' && c <= U'я' && c != U'ё') return glyphFor((char16_t)(c - 0x20));
  if (c >= U'А' && c <= U'Я' && c != U'Ё') return glyphFor((char16_t)(c + 0x20));
  return nullptr; // неизвестный символ -> пробел
}

