#pragma once

// --------------------------- Wi-Fi ------------------------------------------
#define WIFI_SSID     "ШКОЛА-WIFI"          // <<< имя вашей сети
#define WIFI_PASS     "пароль"              // <<< пароль
#define HTTP_PORT     8765                  // веб-редактор: http://IP-ESP32:8765

// --------------------------- Доступ (PIN) -----------------------------------
// PIN по умолчанию «0000» — лента открывается БЕЗ реального пароля:
// на сайте/в приложении достаточно нажать «Войти» (поле кода можно оставить
// пустым или ввести 0000). Чтобы включить настоящую защиту, поставьте сюда
// любой другой код, например: #define PIN_DEFAULT 1234
#define PIN_DEFAULT   0000

// ------------------- Панели (DMD / HUB75, библиотека SmartLEDMatrix) --------
// 3 панели 8x32 => общая лента 8 строк x 96 колонок.
// Если панели запитаны через один HUB75-шлейф и склеены в ряд — используйте
// вариант A (цепочка). Если к каждой панели свой шлейф — вариант B.
#include <SmartLED_ShiftType.h>
#include <SmartLED_MatrixMapper.h>
//#include <SmartLED_80x8_RFM2169.h>   // раскомментируйте, если у вас готовый
                                       // маппер RFM2169 (8x8 модули 2шт в столбик)

// --- Вариант A: цепочка из трёх панелей на одном HUB75-выходе ---------------
#define PANELS_CHAIN      1
#define PANELS_SEPARATE   2
#define PANEL_LAYOUT      PANELS_CHAIN      // <<< выберите

#define CHAIN_NUM_COLS    96                // всего колонок (3 x 32)
#define CHAIN_NUM_ROWS    8                 // строк DMD
#define CHAIN_MODULES_W   32                // ширина одной панели в пикселях

// --- Вариант B: три независимых HUB75-выхода (по одному на панель) ----------
#define SEP_NUM_PANELS    3
#define SEP_COLS          32
#define SEP_ROWS          8

// --------------------------- Буфер и тайминги -------------------------------
// RAM ESP32 ~520 КБ. Кадр 8x96 RGB = 2304 байта.
// 5-минутный буфер при 10 к/с = 3000 кадров => храним ЧЕРНО-БЕЛЫЕ кадры
// (1 байт/пиксель = 2304 байта/кадр). Цветные эффекты рисуются на лету.
#define BUFFER_SECONDS    300               // 5 минут в RAM
#define TARGET_FPS        10                // кадров в секунду в буфере
#define MAX_FRAMES        (BUFFER_SECONDS * TARGET_FPS)   // 3000 кадров

#define PREBUFFER_SECONDS 10                // сколько секунд нового качаем заранее
#define FETCH_LEAD_SECONDS 5                // за 5 сек до конца старых просим новые
#define DELETE_LEAD_SECONDS 5               // последние 5 сек старых -> удаляем
#define FETCH_TIMEOUT_MS  (5*60*1000)       // 5 минут на ответ ПК, иначе ошибка

// ------------------------------ Bluetooth -----------------------------------
#define BT_DEVICE_NAME    "NY-BANNER"       // виден в приложении на телефоне/ПК

// ------------------------- Прочее --------------------------------------------
#define DEFAULT_BRIGHTNESS  120             // 0..255
